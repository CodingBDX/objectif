create or replace function public.block_disposable_email() returns trigger
language plpgsql security definer set search_path = public as $q$
declare d text := lower(split_part(new.email, '@', 2));
begin
  if d <> '' and exists (select 1 from public.disposable_domains x where d = x.domain or d like '%.' || x.domain) then
    raise exception 'email_jetable' using errcode = 'P0001';
  end if;
  return new;
end $q$;

drop trigger if exists block_disposable_email on auth.users;
create trigger block_disposable_email before insert on auth.users
for each row execute function public.block_disposable_email();

